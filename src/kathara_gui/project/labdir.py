"""Materialising a :class:`Topology` as a Kathara lab directory on disk.

Produces exactly the layout Kathara expects::

    <lab>/
      lab.conf
      r1.startup
      r1/etc/frr/daemons      (routers with daemons enabled)

Every write goes through :func:`write_text_lf`, so a lab generated on Windows
is byte-identical to one generated on Linux and its scripts run correctly
inside the container either way.
"""

from __future__ import annotations

from pathlib import Path

from kathara_gui.domain.codec import startup
from kathara_gui.domain.codec.labconf import serialize
from kathara_gui.domain.model import KNOWN_DAEMONS, Node, Topology
from kathara_gui.fsutil import write_text_lf

__all__ = ["write_lab", "render_frr_daemons"]


def render_frr_daemons(node: Node) -> str:
    """Render ``/etc/frr/daemons``, which FRR reads to decide what to launch.

    The file lists every daemon with ``yes``/``no``; omitting one entirely
    leaves FRR using its own default, so all known daemons are listed
    explicitly and the enabled ones flipped on.
    """
    enabled = set(node.daemons)
    lines = [
        "# Generated by Kathara GUI. Edits are overwritten on the next save.",
        # zebra underpins the others; enabling a protocol without it is a
        # mistake that produces a silently dead router.
        *(f"{daemon}={'yes' if daemon in enabled or daemon == 'zebra' else 'no'}"
          for daemon in sorted(KNOWN_DAEMONS)),
    ]
    return "\n".join(lines) + "\n"


def write_lab(topology: Topology, destination: Path) -> Path:
    """Write ``topology`` into ``destination``, creating it if needed.

    Returns the directory written. Existing generated files are overwritten;
    unrelated files in the directory are left alone, so a lab that also holds
    a PDF manual or student notes survives a regeneration.
    """
    destination = Path(destination)
    destination.mkdir(parents=True, exist_ok=True)

    write_text_lf(destination / "lab.conf", serialize(topology))

    for filename, content in startup.render_all(topology).items():
        write_text_lf(destination / filename, content)

    for node in topology.nodes:
        if node.daemons:
            write_text_lf(destination / node.name / "etc" / "frr" / "daemons",
                          render_frr_daemons(node))

    return destination
