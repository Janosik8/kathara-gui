"""Generation of per-device ``.startup`` scripts.

Kathara runs ``<device>.startup`` inside the container at boot. This is where
the addressing plan becomes real configuration: without it the interfaces exist
but carry no addresses, which is the state a student would otherwise have to
fix by hand on every single deployment.

The scripts are plain ``sh``. They are executed by Linux regardless of the host
that generated them, so they must be written with
:func:`kathara_gui.fsutil.write_text_lf`.
"""

from __future__ import annotations

import ipaddress
import re

from kathara_gui.domain.model import Node, Topology

HEADER = "# Generated by Kathara GUI. Edits are overwritten on the next save."

#: ``ip address add 10.0.0.1/24 dev eth0`` and its abbreviations. iproute2
#: accepts ``addr``/``a`` for ``address``, and real labs use all of them.
_IP_ADDRESS = re.compile(
    r"\bip\s+(?:-\S+\s+)*a(?:dcdr|ddr(?:ess)?)?\s+add\s+(\S+)\s+dev\s+(\w+)",
    re.IGNORECASE,
)

#: ``ifconfig eth0 10.0.0.1 netmask 255.255.255.0`` — the Netkit-era form, still
#: what many published teaching labs contain.
_IFCONFIG = re.compile(
    r"\bifconfig\s+(\w+)\s+(\d+\.\d+\.\d+\.\d+)"
    r"(?:\s*/\s*(\d{1,2})|\s+netmask\s+(\d+\.\d+\.\d+\.\d+))?",
    re.IGNORECASE,
)

_INTERFACE_NUMBER = re.compile(r"^eth(\d+)$", re.IGNORECASE)


def render_startup(node: Node) -> str:
    """Build the ``.startup`` script for one device.

    Returns an empty string when there is nothing to do, so the caller can
    skip writing a file that would only contain a comment.
    """
    body: list[str] = []

    for iface in sorted(node.interfaces, key=lambda i: i.number):
        # Kathara usually brings interfaces up itself, but doing it explicitly
        # makes the script correct in isolation and harmless when redundant.
        body.append(f"ip link set {iface.name} up")
        if iface.ip:
            body.append(f"ip address add {iface.ip} dev {iface.name}")

    for address in node.loopbacks:
        # lo is up in every container already; only the address is ours.
        body.append(f"ip address add {address} dev lo")

    if node.kind == "switch":
        # A switch forwards rather than terminates traffic.
        body.append("sysctl -w net.ipv4.ip_forward=1")

    if node.daemons:
        # The FRR image reads /etc/frr/daemons, written separately; starting
        # the service here covers images that do not auto-start it.
        body.append("systemctl start frr 2>/dev/null || /etc/init.d/frr start 2>/dev/null || true")

    if not body:
        return ""
    return "\n".join([HEADER, *body]) + "\n"


def _as_cidr(address: str, prefix: str | None, netmask: str | None) -> str | None:
    """Normalise the several ways a startup script can spell an address."""
    try:
        if "/" in address:
            return str(ipaddress.ip_interface(address))
        if prefix:
            return str(ipaddress.ip_interface(f"{address}/{prefix}"))
        if netmask:
            return str(ipaddress.ip_interface(f"{address}/{netmask}"))
        # No mask at all. ifconfig would infer one from the class; guessing on
        # the user's behalf is worse than leaving the field for them to fill.
        return None
    except ValueError:
        return None


def parse_startup(text: str) -> dict[int, str]:
    """Addresses a ``.startup`` script assigns, keyed by interface number.

    The point is import: a lab written by hand, or by Netkit, keeps its
    addressing here and nowhere else, so reading only ``lab.conf`` produces a
    topology the validator then reports as unaddressed — while the addresses
    were on disk the whole time.

    Deliberately narrow. This recognises the two forms that actually assign an
    address and ignores everything else, rather than trying to interpret shell.
    A script doing something clever keeps working; its addresses simply are not
    lifted into the model, which is the safe direction to fail.
    """
    found: dict[int, str] = {}

    for line in text.splitlines():
        # A commented-out address is not configuration.
        statement = line.split("#", 1)[0]
        if not statement.strip():
            continue

        for match in _IP_ADDRESS.finditer(statement):
            address, device = match.group(1), match.group(2)
            number = _INTERFACE_NUMBER.match(device)
            cidr = _as_cidr(address, None, None)
            if number and cidr:
                # First assignment wins: a second is a secondary address, and
                # the model holds one per interface.
                found.setdefault(int(number.group(1)), cidr)

        for match in _IFCONFIG.finditer(statement):
            device, address, prefix, netmask = match.groups()
            number = _INTERFACE_NUMBER.match(device)
            cidr = _as_cidr(address, prefix, netmask)
            if number and cidr:
                found.setdefault(int(number.group(1)), cidr)

    return found


#: ``ifconfig lo:0 10.255.0.1 netmask 255.255.255.255``: Netkit labs put extra
#: loopback addresses on aliases.
_IFCONFIG_LO = re.compile(
    r"\bifconfig\s+lo(?::\w+)?\s+(\d+\.\d+\.\d+\.\d+)"
    r"(?:\s*/\s*(\d{1,2})|\s+netmask\s+(\d+\.\d+\.\d+\.\d+))?",
    re.IGNORECASE,
)


def parse_loopbacks(text: str) -> list[str]:
    """Addresses a ``.startup`` script puts on ``lo``, apart from 127.0.0.1.

    The counterpart of :func:`parse_startup` for the one interface that is not
    ``ethN``, so a lab written by hand keeps its router IDs on import.
    """
    found: list[str] = []
    for line in text.splitlines():
        statement = line.split("#", 1)[0]
        candidates = [
            _as_cidr(m.group(1), None, None)
            for m in _IP_ADDRESS.finditer(statement)
            if m.group(2).lower() == "lo"
        ]
        candidates += [
            _as_cidr(address, prefix, netmask)
            for address, prefix, netmask in _IFCONFIG_LO.findall(statement)
        ]
        for cidr in candidates:
            if cidr and not ipaddress.ip_interface(cidr).is_loopback and cidr not in found:
                found.append(cidr)
    return found


def render_all(topology: Topology) -> dict[str, str]:
    """Map ``<device>.startup`` filenames to their contents.

    Devices needing no startup actions are omitted rather than given an empty
    file, keeping the lab directory free of noise.
    """
    result: dict[str, str] = {}
    for node in topology.nodes:
        content = render_startup(node)
        if content:
            result[f"{node.name}.startup"] = content
    return result
